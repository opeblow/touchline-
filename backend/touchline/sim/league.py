def _player(
    rng: np.random.Generator, team_code: str, idx: int, pos: str, used: set[str], quality: float
) -> Player:
    nation = str(rng.choice(NATIONS, p=NATION_WEIGHTS))
    for _ in range(50):
        first = str(rng.choice(FIRST[nation]))
        last = str(rng.choice(LAST[nation]))
        name = f"{first} {last}"
        if name not in used:
            break
    used.add(name)
    pace, passing, finishing, defending = ATTR_PROFILE[pos]

    def jitter(v: float) -> float:
        return float(np.clip(v * (0.85 + 0.3 * quality) + rng.normal(0, 0.06), 0.15, 0.97))

    return Player(
        id=f"{team_code.lower()}-{idx:02d}",
        name=name,
        short_name=last,
        number=int([1, 2, 5, 6, 3, 4, 8, 10, 7, 9, 11, 13, 15, 12, 14, 16, 17, 19][idx]),
        position=pos,
        pace=jitter(pace),
        passing=jitter(passing),
        finishing=jitter(finishing),
        defending=jitter(defending),
        stamina=float(np.clip(rng.normal(0.72, 0.1), 0.4, 0.97)),
        nationality=nation,
    )


@lru_cache(maxsize=4)
def build_league(seed: int = 2026) -> tuple[Team, ...]:
    rng = np.random.default_rng(seed)
    used: set[str] = set()
    teams = []
    for i, (
        name,
        short,
        code,
        city,
        primary,
        secondary,
        press,
        poss,
        direct,
        width,
        tempo,
        formation,
    ) in enumerate(CLUBS):
        quality = float(np.clip(0.75 - i * 0.012 + rng.normal(0, 0.05), 0.35, 0.95))
        players = [_player(rng, code, j, pos, used, quality) for j, pos in enumerate(SQUAD_POSITIONS)]
        teams.append(
            Team(
                id=code.lower(),
                name=name,
                short_name=short,
                code=code,
                city=city,
                primary=primary,
                secondary=secondary,
                style=TeamStyle(
                    press=press,
                    possession=poss,
                    directness=direct,
                    width=width,
                    tempo=tempo,
                    formation=formation,
                ),
                players=players,
            )
        )
    return tuple(teams)


def get_team(team_id: str, seed: int = 2026) -> Team:
    for team in build_league(seed):
        if team.id == team_id.lower() or team.code == team_id.upper():
            return team
    raise KeyError(f"Unknown team '{team_id}'")
